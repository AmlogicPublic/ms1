  //=================================================
  dis_x0 = img_width / block_xnum;
  dis_y0 = img_height / block_ynum;

  printf("dis_x0 = %d, dis_y0 = %d\n", dis_x0, dis_y0);

  if ((img_width % block_xnum) == 0)
    dis_x1 = dis_x0;
  else
    dis_x1 = dis_x0 + 1;

  if ((img_height % block_ynum) == 0)
    dis_y1 = dis_y0;
  else
    dis_y1 = dis_y0 + 1;

  dis[0] = dis_x0 * dis_y0;
  dis[1] = dis_x1 * dis_y0;
  dis[2] = dis_x0 * dis_y1;
  dis[3] = dis_x1 * dis_y1;

  printf("dis[0] = %d\n", dis[0]);

