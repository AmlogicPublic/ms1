  // Wr_reg_bits(LDC_REG_HW_HIST_ADDR_BASE     ,base_addr+0x0005ac00,0,32); //reg_hw_hist_addr_base
  Wr(LDC_REG_HW_DUTY_INFO_ADDR_BASE, (uint32_t)(base_addr + 0x00000000)); // reg_hw_duty_info_addr_base
