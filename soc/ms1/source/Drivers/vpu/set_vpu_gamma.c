void set_lcd_gamma_new(MNT_GAMMA_t *mnt_vpu_gamma)
{
    uint16_t i;
    if(mnt_vpu_gamma->gamma_en) {
        Wr(LCD_GAMMA_ADDR_PORT0,0x200);
        for(i=0;i<257;i++) {
            Wr(LCD_GAMMA_DATA_PORT0,(mnt_vpu_gamma->gamma_lut_r[i]<<20)|
                                    (mnt_vpu_gamma->gamma_lut_g[i]<<10)|
                                     mnt_vpu_gamma->gamma_lut_b[i]     );
        }
        Wr(LCD_GAMMA_CNTL_PORT0, (1 << 0) | (1 << 6));
    }
}

